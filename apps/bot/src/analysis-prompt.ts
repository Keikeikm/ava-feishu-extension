import type { DatasetInfo } from './types.js';

export function analysisPrompt(query: string, info: DatasetInfo, context = '', withCharts = false): string {
  const exploratory = /探索性(?:数据)?分析|\beda\b/i.test(query);
  const overview = /^(?:请|帮我|请帮我)?(?:分析|看|看看)(?:一下|下)?(?:这个|这份|这组|一下)?(?:数据|表格|表)?[。！!\s]*$/.test(query) || /^(整体分析|总体分析|全面分析|整体概览|概览)$/.test(query);
  const goal = exploratory
    ? '用户希望做探索性数据分析。先核对样本量和关键字段的缺失情况，再用聚合查询检查重要变量的分布和组间差异。数值字段优先用中位数和分位数，类别和标签优先用频次、分组比例和各组样本量。若存在明确的标签字段，优先选与标签相关的有意义分组。选择最值得报告的两到三个方向，并指出缺失或样本量如何影响解读。'
    : overview
    ? '用户希望获得整体判断。请主动完成聚合统计：整体核心指标；若有时间字段，比较实际存在的相邻时期及变化率；若有分类字段，比较贡献和增速差异，优先找逆势下滑、效率偏低或增长集中的类别；若有收入和利润，计算加权利润率。最多选择三个有意义的分析方向。没有数值度量时，可分析频次、集中度和数据质量。最后只选一个主结论和至多一个次要风险，不要全面罗列统计。'
    : '聚焦用户当前问题，选择适合的比较基准和统计口径；结合历史理解追问。';
  const multiTable = info.profile.models.length > 1 ? `
- 整体分析须覆盖每张表。分别计算各表自己的行数和至少一项有意义的指标或分布，在回复中用表名标明归属。空表需明确说明。用户指定表名时优先分析指定表。
- 比较前先核对粒度、字段口径和样本量。仅在有可信关联键时连接，检查键唯一性和匹配率，必要时先分别聚合，避免多对多重复计数。没有可靠关联键时分别分析。` : '';
  const labelScope = info.labelCaveat ? `
- 标签来源约束：${info.labelCaveat} 如果用户询问生还差异，使用“文件标签”或“标记为生还”描述比例和图表。可以按性别与舱位交叉分组、比较各组样本量和票价中位数，或比较已知年龄和缺失年龄样本。不要将规则生成的标签当成模型评估或因果依据。` : '';
  const charts = withCharts ? `
- 图表和结论必须使用本次执行的同一份结果。简单分组比较可直接返回维度和聚合值（一行一个地区、类别或时间点），不要混入总计行。整体分析、探索性数据分析或多维比较必须把支撑主结论的图表数据作为查询结果返回，不能只返回单行宽表或嵌套 JSON。
- 对整体分析或多维比较，可使用 CTE 聚合再 UNION ALL：每个图表数据点返回四列 chart_kind（line 时间趋势、bar 分类比较、column 柱状图、pie 完整且非负的构成）、chart_title（简体中文且写清指标与单位，组内相同）、chart_label（时期或类别）、chart_value（计算得到的数值）。每图至少两个不同标签，最多两张图。额外的统计证据可以作为其他列或 chart_kind 为空的行返回。相同图不要混入其他单位、总体和子组；无可比数据时不必凑图。
- 用真实时间顺序比较时期。图表标题使用标准的时间表述，例如「近 10 年内容数量」「未来 3 年预测」。至少一张图应直接对应主结论的指标，其余图对应另一条发现。服从用户指定的筛选和统计口径。比例如需用百分数作图，数值乘 100、保留两位小数并在标题注明 %。先选最能支撑结论的图，不要为了画图扩大问题范围。` : '';
  return `${context}\n当前问题：${query}\n${goal}
分析要求：
- 用真实查询计算结论所需的总量、差异、变化率、占比或比率。比率采用正确分母，利润率使用总利润/总收入。比较前检查时期是否可比。
- 整体判断必须使用聚合查询，可用 CTE 和 UNION ALL 在一个只读 SELECT 中返回多项统计。不要用 SELECT * 或明细列表代替分析；用户明确要明细时除外。
- 先识别实际字段含义和粒度。不得把数值 ID 当度量，不得混加单位不同的指标。数据或用户未明确单位时，文字和图表只写指标名，不能自行添加货币或数量单位（如元、美元、件）。字段缺失或口径冲突时说明缺什么，并提出一个具体澄清问题。
- 多因素比较同时计算样本数、分母与分组比例，必要时按另一变量分层。报告小样本和关键字段的缺失量，缺失值保留为空，不当作 0。偏态数值优先比较中位数和分位数。
- 数据质量背景（仅作限制说明，不替代业务分析）：${JSON.stringify(info.profile.models.map(m => ({ table: m.name, rows: m.metrics.row_count, nulls: m.columns.filter(c => Number(c.metrics.null_count) > 0).map(c => c.name) })))}。${multiTable}${labelScope}${charts}
回复要求（最终回答请全部放在 conclusion 内容中）：
用简体中文，控制在 ${multiTable && overview ? '每张表 100 字以内，另加整体结论和追问' : '220 字左右'}，按以下三段组织：
【结论】只用一句话直接回答问题，指出最重要的变化或差异。仅在有明确证据时提示风险；小样本或单期差异不足以判断长期趋势。
【关键依据】${multiTable && overview ? '每张表至少一句，写明表名。' : '最多两条，每条一句，每条最多两个数值。'}只保留支持结论的比较或比例，避免把图表里的数值逐项重述。不能超出查询结果推断，不得把相关关系写成因果。
【下一步】只提出一个针对最重要发现、能用当前表格继续计算的问题。若验证确实需要未提供的字段，明确请用户补充哪个字段及用途，不能把该字段写成已经存在。
必要限制用一句话说明；没有证据时明确不确定性。用户只说“分析一下”时按上述整体分析目标执行，无需指责问题不完整。不要输出原始行、SQL、文件清单、查询过程或 JSON 结构。`;
}
